"""Fit a small ReLU cutoff classifier and export fixed-point C weights."""

import argparse
from pathlib import Path

import numpy as np


def sigmoid(logit):
    return 1 / (1 + np.exp(-np.clip(logit, -25, 25)))


def train(features, labels, epochs):
    random = np.random.default_rng(61342)
    weights = [random.normal(0, 0.3, (features.shape[1], 8)), np.zeros(8),
               random.normal(0, 0.3, 8), np.zeros(1)]
    first_moments = [np.zeros_like(weight) for weight in weights]
    second_moments = [np.zeros_like(weight) for weight in weights]
    step = 0
    for epoch in range(epochs):
        order = random.permutation(len(labels))
        for start in range(0, len(order), 512):
            batch = order[start:start + 512]
            x, y = features[batch], labels[batch]
            w, b, out, bias = weights
            hidden = np.maximum(0, x @ w + b)
            error = (sigmoid(hidden @ out + bias) - y) / len(batch)
            hidden_error = (hidden > 0) * (error[:, None] * out)
            gradients = (x.T @ hidden_error, hidden_error.sum(axis=0),
                         hidden.T @ error, np.array([error.sum()]))
            step += 1
            for weight, gradient, first, second in zip(
                    weights, gradients, first_moments, second_moments):
                first[:] = 0.9 * first + 0.1 * gradient
                second[:] = 0.999 * second + 0.001 * gradient ** 2
                weight -= 0.003 * (first / (1 - 0.9 ** step)) / (
                    np.sqrt(second / (1 - 0.999 ** step)) + 1e-8)
    return weights


def export(path, weights):
    hidden, bias, output, _ = weights
    quantized = [np.rint(hidden.T * 256), np.rint(bias * 4096), np.rint(output * 256)]
    if any(np.any(np.abs(values) > 32767) for values in quantized):
        raise ValueError("Weights exceed int16 range")
    hidden, bias, output = [values.astype(int) for values in quantized]

    def c_row(values):
        return "{ " + ", ".join(str(value) for value in values) + " }"

    rows = "\n".join(f"    {c_row(row)}," for row in hidden)
    path.write_text(
        "/* Generated by training/tuning/train_cutoff_policy.py. */\n"
        "static const int16_t cutoff_policy_hidden_weight"
        "[CUTOFF_POLICY_HIDDEN][CUTOFF_POLICY_INPUTS] = {\n"
        f"{rows}\n}};\n"
        f"static const int16_t cutoff_policy_hidden_bias[] = {c_row(bias)};\n"
        f"static const int16_t cutoff_policy_output_weight[] = {c_row(output)};\n",
        encoding="ascii",
    )


def load(path):
    data = np.loadtxt(path, delimiter=",", ndmin=2)
    if data.shape[1] != 17 or len(np.unique(data[:, 15])) != 2:
        raise ValueError(f"{path} must contain 15 features, a binary label, and node cost")
    return data[:, :15] / 16, data[:, 15]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("samples", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--validation", type=Path)
    parser.add_argument("--epochs", type=int, default=24)
    args = parser.parse_args()
    features, labels = load(args.samples)
    weights = train(features, labels, args.epochs)
    export(args.output, weights)
    print(f"Trained on {len(labels):,} searches ({labels.mean():.1%} cutoffs)")
    if args.validation:
        x, y = load(args.validation)
        w, b, out, bias = weights
        logit = np.maximum(0, x @ w + b) @ out + bias
        loss = (np.logaddexp(0, logit) - y * logit).mean()
        prior = labels.mean()
        prior_loss = -(y.mean() * np.log(prior) + (1 - y.mean()) * np.log1p(-prior))
        print(f"Validation ({len(y):,} searches) log loss {loss:.4f}, prior {prior_loss:.4f}")


if __name__ == "__main__":
    main()
